// MARK: - Param Generator
// Generates typed Swift parameter structs from OpenAPI requestBody schemas and query parameters.
// Each POST operation gets a {Resource}{Action}Params struct with all fields typed.
// Each GET operation with query params beyond `expand` (list, search, …) gets one too,
// e.g. CustomerListParams, CustomerSearchParams.
// Nested objects become sub-structs (up to `maxDepth` levels, then [String: String]), and
// `anyOf` unions become enums with a case per form.
//
// Every top-level params struct includes an optional `expand: [String]?` field.

import Foundation

struct ParamGenerator {
    let spec: OpenAPISpec
    let parser: SpecParser
    /// Records every place a param falls back to a looser type than the spec describes
    var fallbacks = ParamFallbacks()
    
    /// Maximum nesting depth for typed sub-structs
    private let maxDepth = 20
    
    // MARK: - Per-Resource Generation
    
    /// Generate param structs for a resource's `paramOperations` as an extension file.
    /// Returns nil if the resource has no POST bodies or GET query params.
    func generate(resource: StripeResource, operations: [ParamOperation]) -> String? {
        guard !operations.isEmpty else { return nil }
        
        var lines: [String] = []
        
        // File header
        lines.append("//")
        lines.append("//  \(resource.swiftTypeName)+Params.swift")
        lines.append("//  StripeKit")
        lines.append("//")
        lines.append("//  Generated by stripe-kit-codegen")
        lines.append("//")
        lines.append("")
        lines.append("import Foundation")
        lines.append("")
        
        // Collect all sub-structs generated during param generation
        var allSubStructs: [(name: String, lines: [String])] = []
        
        for (action, schema, requiredFields) in operations {
            let stem = "\(resource.swiftTypeName)\(action)"
            let (structLines, subStructs) = generateParamStruct(
                stem: stem,
                schema: schema,
                requiredFields: requiredFields,
                depth: 0
            )
            lines.append(contentsOf: structLines)
            lines.append("")
            allSubStructs.append(contentsOf: subStructs)
        }
        
        // Emit all sub-structs. Two operations can reach the same nested params under the same
        // name (POST /v1/treasury/financial_accounts/{id} `features` and the `updateFeatures`
        // route both give FinancialAccountUpdateFeatures…); emit those once. A name reused for a
        // different shape would be ambiguous Swift, so stop generation instead.
        var emitted: [String: [String]] = [:]
        for (name, subLines) in allSubStructs {
            if let existing = emitted[name] {
                precondition(existing == subLines, "Params struct \(name) generated twice with different fields")
                continue
            }
            emitted[name] = subLines
            lines.append(contentsOf: subLines)
            lines.append("")
        }
        
        return lines.joined(separator: "\n")
    }
    
    // MARK: - Struct Generation
    
    /// Generate a single param struct from an inline schema.
    /// `stem` is the name without "Params" suffix, e.g. "AccountCreate".
    /// Top-level structs get "Params" suffix: "AccountCreateParams".
    /// Sub-structs use plain stem: "AccountCreateBusinessProfile".
    private func generateParamStruct(
        stem: String,
        schema: PropertyObject,
        requiredFields: Set<String>,
        depth: Int
    ) -> (lines: [String], subStructs: [(name: String, lines: [String])]) {
        let structName = depth == 0 ? "\(stem)Params" : stem
        var lines: [String] = []
        var subStructs: [(name: String, lines: [String])] = []
        
        let properties = schema.properties ?? [:]
        let sorted = properties.sorted { $0.key < $1.key }
        
        lines.append(contentsOf: docComment(schema.description))
        lines.append("public struct \(structName): StripeParams {")
        
        // Required fields first, then optional, sorted alphabetically within each group.
        // Each type is resolved once, which also generates the nested types it needs.
        let ordered = sorted.filter { requiredFields.contains($0.key) } + sorted.filter { !requiredFields.contains($0.key) }
        let fields = ordered.map { propName, prop in
            (
                name: escapedSwiftName(snakeToCamel(propName)),
                type: resolveType(prop, parentStem: stem, propName: propName, depth: depth, subStructs: &subStructs),
                isRequired: requiredFields.contains(propName),
                description: prop.description
            )
        }
        
        for field in fields {
            lines.append(contentsOf: docComment(field.description, indent: "    "))
            lines.append("    public var \(field.name): \(field.type)\(field.isRequired ? "" : "?")")
        }
        
        // Only top-level params have expand (sub-types don't make separate API calls)
        if depth == 0 && !properties.keys.contains("expand") {
            lines.append("    /// Specifies which fields to expand in the response.")
            lines.append("    public var expand: [String]?")
        }
        
        // Memberwise initializer: required params first, optional ones defaulting to nil
        lines.append("")
        if fields.isEmpty {
            lines.append("    public init() {}")
        } else {
            let initParams = fields.map { "\($0.name): \($0.type)\($0.isRequired ? "" : "? = nil")" }
            lines.append("    public init(\(initParams.joined(separator: ", "))) {")
            for field in fields {
                lines.append("        self.\(field.name) = \(field.name)")
            }
            lines.append("    }")
        }
        
        // CodingKeys
        let needsCodingKeys = sorted.contains { snakeToCamel($0.key) != $0.key }
        if needsCodingKeys {
            lines.append("")
            lines.append("    public enum CodingKeys: String, CodingKey {")
            for (propName, _) in sorted {
                let swiftName = snakeToCamel(propName)
                if swiftName == propName {
                    lines.append("        case \(escapedSwiftName(swiftName))")
                } else {
                    lines.append("        case \(escapedSwiftName(swiftName)) = \"\(propName)\"")
                }
            }
            if depth == 0 && !properties.keys.contains("expand") {
                lines.append("        case expand")
            }
            lines.append("    }")
        }
        
        lines.append("}")
        
        return (lines, subStructs)
    }
    
    // MARK: - Type Resolution
    
    /// The Swift type for a param schema. Generates the nested types it needs (structs for
    /// objects, enums for `anyOf` unions) into `subStructs`, named `{parentStem}{PropName}`.
    /// Every place the type is looser than the schema is recorded in `fallbacks`.
    private func resolveType(
        _ prop: PropertyObject,
        parentStem: String,
        propName: String,
        depth: Int,
        subStructs: inout [(name: String, lines: [String])]
    ) -> String {
        let stem = "\(parentStem)\(capitalize(snakeToCamel(propName)))"
        
        if let anyOf = prop.anyOf, !anyOf.isEmpty {
            return resolveAnyOf(anyOf, parentStem: parentStem, propName: propName, depth: depth, subStructs: &subStructs)
        }
        
        if let ref = prop.ref {
            return parser.schemaNameToSwiftType(refToSchemaName(ref))
        }
        
        // Enum. A "clear-only" enum whose sole value is "" gets no generated type
        // (generateEnum drops ""), so fall through to the base type instead.
        if let enumCases = prop.enum, enumCases.contains(where: { !$0.isEmpty }) {
            return stem
        }
        
        // Object with fields → generated struct
        if let props = prop.properties, !props.isEmpty {
            guard depth < maxDepth else {
                fallbacks.record(parentStem, propName, "nested deeper than \(maxDepth) → [String: String]")
                return "[String: String]"
            }
            let (subLines, nestedSubs) = generateParamStruct(
                stem: stem,
                schema: prop,
                requiredFields: Set(prop.required ?? []),
                depth: depth + 1
            )
            subStructs.append((stem, subLines))
            subStructs.append(contentsOf: nestedSubs)
            return stem
        }
        
        switch prop.type {
        case "string":
            return "String"
        case "integer":
            return prop.isUnixTime ? "Date" : "Int"
        case "number":
            return "Double"
        case "boolean":
            return "Bool"
        case "array":
            guard let items = prop.items else {
                fallbacks.record(parentStem, propName, "array without items → [String]")
                return "[String]"
            }
            return "[\(resolveType(items, parentStem: parentStem, propName: propName, depth: depth, subStructs: &subStructs))]"
        case "object":
            // A map, e.g. metadata ([String: String]) or currency_options ([String: {Stem}])
            if let values = prop.additionalProperties {
                return "[String: \(resolveType(values, parentStem: parentStem, propName: propName, depth: depth, subStructs: &subStructs))]"
            }
            // `properties: {}` is a hash the spec defines as empty (e.g. payment_method_data[bizum]),
            // so nothing is lost; only an object with no shape at all is a fallback.
            if prop.properties == nil {
                fallbacks.record(parentStem, propName, "free-form object → [String: String]")
            }
            return "[String: String]"
        default:
            fallbacks.record(parentStem, propName, "type \(prop.type ?? "missing") → String")
            return "String"
        }
    }
    
    private func resolveAnyOf(
        _ variants: [PropertyObject],
        parentStem: String,
        propName: String,
        depth: Int,
        subStructs: inout [(name: String, lines: [String])]
    ) -> String {
        // Filter out empty-string enum variants (Stripe uses "" to mean "unset")
        let nonEmpty = variants.filter { $0.enum != [""] }
        
        // One real variant: it's that variant's type
        if nonEmpty.count == 1, let single = nonEmpty.first {
            return resolveType(single, parentStem: parentStem, propName: propName, depth: depth, subStructs: &subStructs)
        }
        
        // `integer | range_query_specs` (list filters like `created`) → shared StripeRangeQuery
        if nonEmpty.count == 2,
           nonEmpty.contains(where: { $0.type == "integer" && $0.enum == nil }),
           nonEmpty.contains(where: { $0.title == "range_query_specs" }) {
            return "StripeRangeQuery"
        }
        
        // Several forms → a generated enum with a case per form
        if let union = generateUnion(nonEmpty, parentStem: parentStem, propName: propName, depth: depth, subStructs: &subStructs) {
            return union
        }
        
        let kinds = nonEmpty.map { variant -> String in
            if let title = variant.title { return title }
            if variant.enum != nil { return "\(variant.type ?? "?") enum" }
            return variant.type ?? variant.ref.map(refToSchemaName) ?? "?"
        }
        fallbacks.record(parentStem, propName, "anyOf \(kinds.joined(separator: " | ")) → String")
        return "String"
    }
    
    // MARK: - Union Generation
    
    /// A union's scalar form: its Swift type, the literal protocol the union takes, that
    /// protocol's init parameter, and how to make the scalar from the literal `value`.
    private typealias UnionScalar = (type: String, literal: String, literalType: String, fromLiteral: String)

    /// The scalar form for a plain (non-enum) scalar schema. A Unix timestamp is a `Date`, which
    /// still takes an integer literal of seconds: `trialEnd: 1_700_000_000`.
    private func unionScalar(_ variant: PropertyObject) -> UnionScalar? {
        guard variant.enum == nil, variant.properties?.isEmpty != false else { return nil }
        switch variant.type {
        case "integer" where variant.isUnixTime:
            return ("Date", "ExpressibleByIntegerLiteral", "integerLiteral value: Int", "Date(timeIntervalSince1970: TimeInterval(value))")
        case "integer": return ("Int", "ExpressibleByIntegerLiteral", "integerLiteral value: Int", "value")
        case "number": return ("Double", "ExpressibleByFloatLiteral", "floatLiteral value: Double", "value")
        case "boolean": return ("Bool", "ExpressibleByBooleanLiteral", "booleanLiteral value: Bool", "value")
        case "string": return ("String", "ExpressibleByStringLiteral", "stringLiteral value: String", "value")
        default: return nil
        }
    }
    
    /// Case name for an object variant, from its spec title minus a `_param(s)` suffix:
    /// secret_key_param → secretKey, card_details_params → cardDetails, card_token → cardToken.
    private func unionObjectCaseName(_ variant: PropertyObject, index: Int) -> String {
        guard let title = variant.title else { return "variant\(index + 1)" }
        var base = title
        for suffix in ["_params", "_param"] where base.hasSuffix(suffix) && base.count > suffix.count {
            base = String(base.dropLast(suffix.count))
            break
        }
        return snakeToCamel(base)
    }
    
    /// Generate an enum for an `anyOf` with several forms, e.g. `trial_end: "now" | timestamp`:
    ///
    ///     public enum SubscriptionCreateTrialEnd: …, ExpressibleByIntegerLiteral {
    ///         case now
    ///         case value(Int)
    ///     }
    ///
    /// Keyword strings become plain cases, a scalar becomes `value(T)` (and the enum takes
    /// that literal: `trialEnd: 1_700_000_000`), object forms become cases carrying a generated
    /// struct. Returns nil for shapes it can't represent (e.g. two different scalars).
    private func generateUnion(
        _ variants: [PropertyObject],
        parentStem: String,
        propName: String,
        depth: Int,
        subStructs: inout [(name: String, lines: [String])]
    ) -> String? {
        let name = "\(parentStem)\(capitalize(snakeToCamel(propName)))"
        
        var keywords: [String] = []
        var scalar: UnionScalar?
        var objects: [(caseName: String, typeName: String)] = []
        
        for (index, variant) in variants.enumerated() {
            if variant.type == "string", let values = variant.enum {
                keywords.append(contentsOf: values.filter { !$0.isEmpty })
            } else if let s = unionScalar(variant) {
                guard scalar == nil else { return nil }
                scalar = s
            } else if let props = variant.properties, !props.isEmpty, depth < maxDepth {
                let caseName = unionObjectCaseName(variant, index: index)
                let typeName = "\(name)\(capitalize(caseName))"
                let (subLines, nestedSubs) = generateParamStruct(
                    stem: typeName,
                    schema: variant,
                    requiredFields: Set(variant.required ?? []),
                    depth: depth + 1
                )
                subStructs.append((typeName, subLines))
                subStructs.append(contentsOf: nestedSubs)
                objects.append((caseName, typeName))
            } else {
                return nil
            }
        }
        
        let keywordCases = keywords.map { (raw: $0, name: enumCaseToSwift($0)) }
        let caseNames = keywordCases.map(\.name) + objects.map(\.caseName) + (scalar == nil ? [] : ["value"])
        guard Set(caseNames).count == caseNames.count else { return nil }
        
        var conformances = ["Codable", "Sendable"]
        if let scalar { conformances.append(scalar.literal) }
        
        var lines: [String] = []
        lines.append("/// One of the forms `\(propName)` accepts.")
        lines.append("public enum \(name): \(conformances.joined(separator: ", ")) {")
        for keyword in keywordCases {
            lines.append("    /// `\(keyword.raw)`")
            lines.append("    case \(escapedSwiftName(keyword.name))")
        }
        for object in objects {
            lines.append("    case \(escapedSwiftName(object.caseName))(\(object.typeName))")
        }
        if let scalar {
            lines.append("    case value(\(scalar.type))")
            lines.append("")
            lines.append("    public init(\(scalar.literalType)) { self = .value(\(scalar.fromLiteral)) }")
        }
        
        // Decoding: keywords and the scalar from a single value, then each object form in turn
        lines.append("")
        lines.append("    public init(from decoder: Decoder) throws {")
        lines.append("        let container = try decoder.singleValueContainer()")
        if !keywordCases.isEmpty {
            lines.append("        if let keyword = try? container.decode(String.self) {")
            lines.append("            switch keyword {")
            for keyword in keywordCases {
                lines.append("            case \"\(keyword.raw)\": self = .\(escapedSwiftName(keyword.name)); return")
            }
            lines.append("            default: break")
            lines.append("            }")
            lines.append("        }")
        }
        if let scalar {
            lines.append("        if let value = try? container.decode(\(scalar.type).self) { self = .value(value); return }")
        }
        for object in objects {
            lines.append("        if let value = try? \(object.typeName)(from: decoder) { self = .\(escapedSwiftName(object.caseName))(value); return }")
        }
        lines.append("        throw DecodingError.dataCorruptedError(in: container, debugDescription: \"No form of \(name) matches\")")
        lines.append("    }")
        
        // Encoding: keywords as their string, the scalar as itself, an object form as its fields
        lines.append("")
        lines.append("    public func encode(to encoder: Encoder) throws {")
        lines.append("        switch self {")
        for keyword in keywordCases {
            lines.append("        case .\(escapedSwiftName(keyword.name)):")
            lines.append("            var container = encoder.singleValueContainer()")
            lines.append("            try container.encode(\"\(keyword.raw)\")")
        }
        for object in objects {
            lines.append("        case .\(escapedSwiftName(object.caseName))(let value):")
            lines.append("            try value.encode(to: encoder)")
        }
        if scalar != nil {
            lines.append("        case .value(let value):")
            lines.append("            var container = encoder.singleValueContainer()")
            lines.append("            try container.encode(value)")
        }
        lines.append("        }")
        lines.append("    }")
        lines.append("}")
        
        subStructs.append((name, lines))
        return name
    }
    
    // MARK: - Enum Generation for Params
    
    /// Generate enums that appear in param properties (e.g., capture_method: automatic|manual)
    func generateParamEnums(resource: StripeResource, operations: [ParamOperation]) -> [String] {
        var lines: [String] = []
        var seenEnumNames = Set<String>()
        
        for (action, schema, _) in operations {
            let stem = "\(resource.swiftTypeName)\(action)"
            let props = schema.properties ?? [:]
            
            for (propName, prop) in props.sorted(by: { $0.key < $1.key }) {
                if let enumCases = prop.enum, !enumCases.isEmpty {
                    let enumName = "\(stem)\(capitalize(snakeToCamel(propName)))"
                    guard !seenEnumNames.contains(enumName) else { continue }
                    seenEnumNames.insert(enumName)
                    lines.append(contentsOf: generateStringEnum(name: enumName, cases: enumCases))
                    lines.append("")
                }
                // Also check anyOf for nested enum cases
                collectNestedEnums(
                    prop: prop,
                    parentName: stem,
                    propName: propName,
                    lines: &lines,
                    depth: 0,
                    seenEnumNames: &seenEnumNames
                )
            }
        }
        
        return lines
    }
    
    private func collectNestedEnums(
        prop: PropertyObject,
        parentName: String,
        propName: String,
        lines: inout [String],
        depth: Int,
        seenEnumNames: inout Set<String>
    ) {
        guard depth < maxDepth else { return }
        
        if let props = prop.properties {
            for (subName, subProp) in props.sorted(by: { $0.key < $1.key }) {
                let subParent = "\(parentName)\(capitalize(snakeToCamel(propName)))"
                if let enumCases = subProp.enum, !enumCases.isEmpty {
                    let enumName = "\(subParent)\(capitalize(snakeToCamel(subName)))"
                    if !seenEnumNames.contains(enumName) {
                        seenEnumNames.insert(enumName)
                        lines.append(contentsOf: generateStringEnum(name: enumName, cases: enumCases))
                        lines.append("")
                    }
                }
                collectNestedEnums(
                    prop: subProp,
                    parentName: subParent,
                    propName: subName,
                    lines: &lines,
                    depth: depth + 1,
                    seenEnumNames: &seenEnumNames
                )
            }
        }
        
        // Recurse into array items
        if prop.type == "array", let items = prop.items {
            // If the array items have an enum directly
            if let enumCases = items.enum, !enumCases.isEmpty {
                let enumName = "\(parentName)\(capitalize(snakeToCamel(propName)))"
                if !seenEnumNames.contains(enumName) {
                    seenEnumNames.insert(enumName)
                    lines.append(contentsOf: generateStringEnum(name: enumName, cases: enumCases))
                    lines.append("")
                }
            }
            // If the array items are objects with properties, recurse into them
            if let itemProps = items.properties {
                for (subName, subProp) in itemProps.sorted(by: { $0.key < $1.key }) {
                    let subParent = "\(parentName)\(capitalize(snakeToCamel(propName)))"
                    if let enumCases = subProp.enum, !enumCases.isEmpty {
                        let enumName = "\(subParent)\(capitalize(snakeToCamel(subName)))"
                        if !seenEnumNames.contains(enumName) {
                            seenEnumNames.insert(enumName)
                            lines.append(contentsOf: generateStringEnum(name: enumName, cases: enumCases))
                            lines.append("")
                        }
                    }
                    collectNestedEnums(
                        prop: subProp,
                        parentName: subParent,
                        propName: subName,
                        lines: &lines,
                        depth: depth + 1,
                        seenEnumNames: &seenEnumNames
                    )
                }
            }
        }
        
        // Recurse into anyOf variants. In a union (several real variants), each object
        // variant's struct is named with a variant suffix (see generateUnion), so its enums are too.
        if let anyOf = prop.anyOf {
            let isUnion = anyOf.filter { $0.enum != [""] }.count > 1
            for (index, variant) in anyOf.enumerated() {
                var variantPropName = propName
                if isUnion, let props = variant.properties, !props.isEmpty {
                    let caseName = unionObjectCaseName(variant, index: anyOf.filter { $0.enum != [""] }.firstIndex { $0 === variant } ?? index)
                    variantPropName = propName + "_" + camelToSnakeForNames(caseName)
                }
                collectNestedEnums(
                    prop: variant,
                    parentName: parentName,
                    propName: variantPropName,
                    lines: &lines,
                    depth: depth,
                    seenEnumNames: &seenEnumNames
                )
            }
        }

        // Recurse into map values (currency_options → [String: {Parent}{Prop}])
        if let values = prop.additionalProperties {
            collectNestedEnums(
                prop: values,
                parentName: parentName,
                propName: propName,
                lines: &lines,
                depth: depth,
                seenEnumNames: &seenEnumNames
            )
        }
    }
    
    // MARK: - Operation Discovery
    
    /// A params struct to generate: `{Resource}{action}Params` from a request body or query schema.
    typealias ParamOperation = (action: String, schema: PropertyObject, required: Set<String>)

    /// The POST operations with a body and GET operations with query params among a resource's
    /// route operations (`RouteGenerator.findOperations`), so each struct is named exactly as
    /// the route that takes it refers to it: `{Resource}{Action}Params`.
    func paramOperations(for resource: StripeResource, routes: [RouteGenerator.RouteOperation]) -> [ParamOperation] {
        var results: [ParamOperation] = []

        for op in routes {
            let schema: PropertyObject?
            if op.httpMethod == "POST" && op.hasBody {
                schema = spec.paths[op.path]?.post?.requestBody?.content?["application/x-www-form-urlencoded"]?.schema
            } else if op.httpMethod == "GET" && op.hasQueryParams {
                schema = spec.paths[op.path]?.get?.queryParametersSchema(description: "Query parameters for `GET \(op.path)`.")
            } else {
                schema = nil
            }
            guard let schema else { continue }
            precondition(
                !results.contains { $0.action == op.action },
                "\(resource.swiftTypeName)\(op.action)Params would be generated twice"
            )
            results.append((op.action, schema, Set(schema.required ?? [])))
        }

        return results.sorted { $0.action < $1.action }
    }
}
/// Params whose Swift type is looser than the spec's (a `String` for an `anyOf`, a
/// `[String: String]` for a free-form object, …). Collected so the coverage check can
/// require each one to be fixed or explicitly accepted.
final class ParamFallbacks: @unchecked Sendable {
    /// "PaymentIntentCreate.off_session" → "anyOf boolean | string enum → String"
    private(set) var entries: [String: String] = [:]

    func record(_ parentStem: String, _ propName: String, _ detail: String) {
        entries["\(parentStem).\(propName)"] = detail
    }
}

/// cardDetails → card_details, so `snakeToCamel` round-trips a generated case name.
private func camelToSnakeForNames(_ name: String) -> String {
    name.reduce(into: "") { result, char in
        if char.isUppercase { result += "_" + char.lowercased() } else { result.append(char) }
    }
}
