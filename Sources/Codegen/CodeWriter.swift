// MARK: - Code Writer
// Builds generated Swift source line by line, indenting nested blocks, so generators write
// `block("public struct X {") { … }` instead of hand-indented strings and closing braces.

struct CodeWriter {
    private(set) var lines: [String] = []
    private var depth = 0
    private static let indentUnit = "    "

    /// The file's header comment and imports, set by `fileHeader`
    fileprivate var header: FileHeader?

    /// The source written so far, after the header if there is one
    var text: String {
        guard let header else {
            return lines.joined(separator: "\n")
        }
        return (header.lines(importingFoundation: usesFoundation) + lines).joined(separator: "\n")
    }

    /// Whether the code (not its comments) names a Foundation type. The generator emits only
    /// `Date`, `Data` and `TimeInterval` from Foundation; the compiler catches anything missed.
    private var usesFoundation: Bool {
        lines.contains { line in
            !line.trimmingPrefix(while: \.isWhitespace).hasPrefix("//")
                && line.contains(/\b(Date|Data|TimeInterval)\b/)
        }
    }

    /// One line at the current indentation. An empty line stays empty.
    mutating func line(_ text: String = "") {
        lines.append(text.isEmpty ? "" : String(repeating: Self.indentUnit, count: depth) + text)
    }

    /// `other`'s lines, each indented to the current depth (they're relative to column 0)
    mutating func append(_ other: [String]) {
        for line in other {
            self.line(line)
        }
    }

    /// The `///` doc comment for a spec description, if it has one
    mutating func doc(_ description: String?) {
        append(docComment(description))
    }

    /// `opener`, then `body` one level deeper, then `closer`
    mutating func block(_ opener: String, closer: String = "}", _ body: (inout CodeWriter) -> Void) {
        line(opener)
        indented(body)
        line(closer)
    }

    /// `body` one level deeper
    mutating func indented(_ body: (inout CodeWriter) -> Void) {
        depth += 1
        body(&self)
        depth -= 1
    }
}

/// A writer for a generated file, which starts with a header comment, then its imports and a
/// blank line. Foundation is imported only when the code uses it (see `CodeWriter.text`), and
/// shouldn't be in `imports`.
func fileHeader(_ fileName: String, module: String = "StripeKit", apiVersion: String? = nil, imports: [String] = []) -> CodeWriter {
    var comment = ["//", "//  \(fileName)", "//  \(module)", "//", "//  Generated by stripe-kit-codegen"]
    if let apiVersion {
        comment.append("//  API Version: \(apiVersion)")
    }
    comment.append("//")

    var writer = CodeWriter()
    writer.header = FileHeader(comment: comment, imports: imports)
    return writer
}

/// A generated file's header comment and the modules it imports besides Foundation
private struct FileHeader {
    var comment: [String]
    var imports: [String]

    func lines(importingFoundation: Bool) -> [String] {
        var importLines: [String] = []
        if importingFoundation {
            // FoundationEssentials, where it's a separate module (Linux, Windows), so apps that
            // don't need the rest of Foundation can leave out its internationalization data
            importLines += [
                "#if canImport(FoundationEssentials)",
                "import FoundationEssentials",
                "#else",
                "import Foundation",
                "#endif",
            ]
        }
        importLines += imports.map { "import \($0)" }

        return comment + [""] + (importLines.isEmpty ? [] : importLines + [""])
    }
}
